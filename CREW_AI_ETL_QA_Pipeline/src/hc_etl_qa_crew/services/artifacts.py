def render_test_cases_csv(suite: TestCaseSuite) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        [
            "test_case_id", "pipeline_name", "title", "objective", "priority", "test_type",
            "quality_dimension", "table_name", "column_name", "requirement_ids",
            "data_quality_ids", "preconditions", "test_data", "steps", "expected_result",
            "sql_template", "automation_candidate", "automation_rationale", "tags",
            "assumptions_or_blockers",
        ]
    )
    for case in suite.test_cases:
        writer.writerow(
            [
                case.id, case.pipeline_name, case.title, case.objective, case.priority,
                case.test_type.value, case.quality_dimension.value, case.table_name,
                case.column_name, "; ".join(case.requirement_ids),
                "; ".join(case.data_quality_ids), " | ".join(case.preconditions),
                " | ".join(case.test_data),
                " | ".join(
                    f"{s.number}. {s.action}" + (f" -> {s.expected}" if s.expected else "")
                    for s in case.steps
                ),
                case.expected_result, case.sql_template, case.automation_candidate.value,
                case.automation_rationale, "; ".join(case.tags),
                " | ".join(case.assumptions_or_blockers),
            ]
        )
    return buffer.getvalue()


def render_traceability_csv(coverage: CoverageReport) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        [
            "requirement_id", "requirement_text", "data_quality_id", "data_quality_text",
            "test_case_ids", "automated_test_case_ids", "coverage_status", "reason",
        ]
    )
    for row in coverage.rows:
        writer.writerow(
            [
                row.requirement_id, row.requirement_text, row.data_quality_id,
                row.data_quality_text, "; ".join(row.test_case_ids),
                "; ".join(row.automated_test_case_ids), row.coverage_status.value, row.reason,
            ]
        )
    return buffer.getvalue()


