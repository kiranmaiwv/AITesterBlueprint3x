def write_ticket_artifacts(result: PipelineResult, run_dir: Path) -> dict[str, str]:
    """Write every artifact for one pipeline run. Returns ``{name: relative path}``."""
    pipeline_dir = run_dir / safe_path_segment(result.pipeline_name)
    pipeline_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    def _write(name: str, content: str, subdir: Path | None = None) -> None:
        target = (subdir or pipeline_dir) / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written[name] = str(target.relative_to(run_dir))

    if result.snapshots:
        snap_dir = pipeline_dir / "snapshots"
        snap_dir.mkdir(parents=True, exist_ok=True)
        for snapshot in result.snapshots:
            snap_dir.joinpath(f"{snapshot.table_name}.json").write_text(
                json.dumps(snapshot.model_dump(mode="json"), indent=2), encoding="utf-8"
            )
    if result.analysis:
        _write("schema_analysis.md", render_schema_analysis_md(result.analysis))
        _write(
            "schema_analysis.json",
            json.dumps(result.analysis.model_dump(mode="json"), indent=2),
        )
    if result.recon_plan:
        _write("reconciliation_strategy.md", render_recon_plan_md(result.recon_plan))
    if result.test_cases:
        _write("test_cases.md", render_test_cases_md(result.test_cases))
        _write("test_cases.csv", render_test_cases_csv(result.test_cases))
    if result.coverage:
        _write("traceability_matrix.csv", render_traceability_csv(result.coverage))
    if result.pytest:
        _write("pytest_automation.md", render_pytest_md(result.pytest))
        py_root = pipeline_dir / "pytest"
        for file in result.pytest.files:
            safe_parts = [safe_path_segment(p) for p in Path(file.path).parts]
            target = py_root.joinpath(*safe_parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(file.content, encoding="utf-8")
            written[file.path] = str(target.relative_to(run_dir))

    manifest = build_ticket_manifest(result)
    manifest["artifacts"] = dict(written)
    (pipeline_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    written["manifest.json"] = str((pipeline_dir / "manifest.json").relative_to(run_dir))

    result.artifact_dir = str(pipeline_dir)
    result.artifacts = written
    return written


def write_run_artifacts(run: RunSummary, output_dir: Path) -> Path:
    """Write the run-level summary and manifest, and return the run directory."""
    run_dir = output_dir / safe_path_segment(run.run_id)
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "run_summary.md").write_text(render_run_summary_md(run), encoding="utf-8")
    (run_dir / "manifest.json").write_text(
        json.dumps(build_run_manifest(run), indent=2), encoding="utf-8"
    )
    run.output_dir = str(run_dir)
    return run_dir


# --------------------------------------------------------------------------
# ZIP
# --------------------------------------------------------------------------
def build_zip(run: RunSummary, pipelines: list[str] | None = None) -> bytes:
    """Bundle artifacts into a ZIP, built on demand rather than kept in memory.

    ``pipelines`` limits the bundle to specific pipeline names; the default is
    the whole run.
    """
    wanted = {p.strip().lower() for p in pipelines} if pipelines else None
    buffer = io.BytesIO()

    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(f"{run.run_id}/run_summary.md", render_run_summary_md(run))
        archive.writestr(
            f"{run.run_id}/manifest.json", json.dumps(build_run_manifest(run), indent=2)
        )
        for result in run.results:
            if wanted and result.pipeline_name.lower() not in wanted:
                continue
            if result.status is PipelineStatus.FAILED and not result.analysis:
                continue
            base = f"{run.run_id}/{safe_path_segment(result.pipeline_name)}"
            for name, content in _ticket_files(result):
                archive.writestr(f"{base}/{name}", content)

    buffer.seek(0)
    return buffer.getvalue()


def _ticket_files(result: PipelineResult) -> list[tuple[str, str]]:
    """The in-memory file list for one pipeline, rendered deterministically."""
    files: list[tuple[str, str]] = []
    if result.snapshots:
        for snapshot in result.snapshots:
            files.append(
                (
                    f"snapshots/{snapshot.table_name}.json",
                    json.dumps(snapshot.model_dump(mode="json"), indent=2),
                )
            )
    if result.analysis:
        files.append(("schema_analysis.md", render_schema_analysis_md(result.analysis)))
        files.append(
            (
                "schema_analysis.json",
                json.dumps(result.analysis.model_dump(mode="json"), indent=2),
            )
        )
    if result.recon_plan:
        files.append(("reconciliation_strategy.md", render_recon_plan_md(result.recon_plan)))
    if result.test_cases:
        files.append(("test_cases.md", render_test_cases_md(result.test_cases)))
        files.append(("test_cases.csv", render_test_cases_csv(result.test_cases)))
    if result.coverage:
        files.append(("traceability_matrix.csv", render_traceability_csv(result.coverage)))
    if result.pytest:
        files.append(("pytest_automation.md", render_pytest_md(result.pytest)))
        for file in result.pytest.files:
            safe = "/".join(safe_path_segment(p) for p in Path(file.path).parts)
            files.append((f"pytest/{safe}", file.content))
    files.append(("manifest.json", json.dumps(build_ticket_manifest(result), indent=2)))
    return files


# --------------------------------------------------------------------------
def _cell(text: str) -> str:
    """Make a string safe for a Markdown table cell."""
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _stamp(value: datetime | None) -> str | None:
    return value.isoformat(timespec="seconds") if value else None
