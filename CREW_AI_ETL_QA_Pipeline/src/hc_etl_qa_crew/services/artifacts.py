"""Deterministic renderers and artifact writing.

Everything here is pure Python over validated Pydantic objects. No LLM output
is used as-is: the agents produce structured data, and these functions decide
exactly how it becomes Markdown, CSV, JSON, pytest and a ZIP.
"""

from __future__ import annotations

import csv
import io
import json
import zipfile
from datetime import datetime
from pathlib import Path

from hc_etl_qa_crew.models import (
    AutomationCandidate,
    CoverageReport,
    PipelineResult,
    PipelineStatus,
    PytestBundle,
    ReconcilePlan,
    RunSummary,
    SchemaAnalysis,
    TestCaseSuite,
)

from .pipelines import safe_path_segment

_GENERATED_NOTE = (
    "> Generated by Healthcare ETL QA Crew. Every item traces to the pipeline "
    "contract and the observed snapshot; anything marked INFERRED or "
    "ASSUMPTION_REQUIRING_CONFIRMATION needs human review before it is treated "
    "as fact."
)


