def render_schema_analysis_md(analysis: SchemaAnalysis) -> str:
    lines = [
        f"# Schema & Transform Analysis — {analysis.pipeline_name}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Summary:** {analysis.summary or '_none_'}",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Fact table | {analysis.fact_table or '—'} |",
        f"| Dimension tables | {', '.join(analysis.dimension_tables) or '—'} |",
        f"| Source system | {analysis.source_system or 'not set'} |",
        f"| Load frequency | {analysis.load_frequency or 'not set'} |",
        f"| Observed via | {analysis.source.value} |",
        "",
    ]

    lines += ["## Requirements", ""]
    reqs = [e for e in analysis.entities if e.entity_type == "requirement"]
    if reqs:
        lines += ["| ID | Requirement | Table | Provenance | Severity |", "| --- | --- | --- | --- | --- |"]
        for e in reqs:
            lines.append(
                f"| {e.id} | {_cell(e.text)} | {e.table_name or '—'} | "
                f"{e.provenance.value} | {e.severity.value} |"
            )
    else:
        lines.append("_No requirements were extracted._")
    lines.append("")

    lines += ["## Data-Quality Rules", ""]
    dqs = [e for e in analysis.entities if e.entity_type == "data_quality"]
    if dqs:
        lines += ["| ID | Rule | Table | Provenance | Severity |", "| --- | --- | --- | --- | --- |"]
        for e in dqs:
            lines.append(
                f"| {e.id} | {_cell(e.text)} | {e.table_name or '—'} | "
                f"{e.provenance.value} | {e.severity.value} |"
            )
    else:
        lines.append("_No data-quality rules were extracted._")
    lines.append("")

    if analysis.transform_rules:
        lines += ["## Transform Rules", "", "| ID | Source | Target | Type | Logic | Risk |", "| --- | --- | --- | --- | --- | --- |"]
        for rule in analysis.transform_rules:
            lines.append(
                f"| {rule.id} | {rule.source_table} | {rule.target_table} | "
                f"{rule.rule_type} | {_cell(rule.logic)} | {rule.risk.value} |"
            )
        lines.append("")

    if analysis.field_profiles:
        lines += ["## Field Profiles", "", "| Table.Column | Type | Nulls | Distinct | Min | Max |", "| --- | --- | --- | --- | --- | --- |"]
        for profile in analysis.field_profiles:
            lines.append(
                f"| {profile.table_name}.{profile.column_name} | {profile.data_type} | "
                f"{profile.nulls_observed} | {profile.distinct_observed} | "
                f"{profile.min_value or '—'} | {profile.max_value or '—'} |"
            )
        lines.append("")

    for title, values in (
        ("Risks", analysis.risks),
        ("Assumptions (require confirmation)", analysis.assumptions),
        ("Missing Information", analysis.missing_information),
        ("Open Questions", analysis.open_questions),
    ):
        lines += [f"## {title}", ""]
        lines += [f"- {v}" for v in values] or ["_none recorded_"]
        lines.append("")
    return "\n".join(lines)


def render_recon_plan_md(plan: ReconcilePlan) -> str:
    lines = [
        f"# Reconciliation & Data-Quality Strategy — {plan.pipeline_name}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Summary:** {plan.summary or '_none_'}",
        "",
    ]

    lines += ["## Reconciliation Strategies", ""]
    if plan.strategies:
        lines += ["| ID | Strategy | Type | Source | Target | Match key | Tolerance |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for strategy in plan.strategies:
            lines.append(
                f"| {strategy.id} | {_cell(strategy.name)} | {strategy.recon_type.value} | "
                f"{strategy.source_table or '—'} | {strategy.target_table or '—'} | "
                f"{', '.join(strategy.match_key) or '—'} | {strategy.tolerance_pct}% |"
            )
    else:
        lines.append("_No reconciliation strategies were produced._")
    lines.append("")

    lines += ["## Data-Quality Rules", ""]
    if plan.quality_rules:
        lines += ["| ID | Rule | Dimension | Table | Column | Threshold | Severity |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for rule in plan.quality_rules:
            lines.append(
                f"| {rule.id} | {_cell(rule.name)} | {rule.dimension.value} | "
                f"{rule.table_name or '—'} | {rule.column_name or '—'} | "
                f"{rule.threshold or '—'} | {rule.severity.value} |"
            )
    else:
        lines.append("_No quality rules were produced._")
    lines.append("")

    for title, values in (
        ("Environment Strategy", plan.environment_strategy),
        ("Execution Order", plan.execution_order),
        ("Entry / Exit Criteria", plan.entry_exit_criteria),
        ("Risks", plan.risks),
        ("Dependencies", plan.dependencies),
        ("Assumptions", plan.assumptions),
        ("Missing Information", plan.missing_information),
    ):
        lines += [f"## {title}", ""]
        lines += [f"- {v}" for v in values] or ["_none recorded_"]
        lines.append("")
    return "\n".join(lines)


def render_test_cases_md(suite: TestCaseSuite) -> str:
    lines = [
        f"# Data-Quality Test Cases — {suite.pipeline_name}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Total test cases:** {len(suite.test_cases)}",
        "",
    ]
    if suite.coverage_notes:
        lines += ["## Coverage Notes", "", suite.coverage_notes.strip(), ""]

    for case in suite.test_cases:
        lines += [
            f"## {case.id} — {case.title}",
            "",
            f"- **Pipeline:** {case.pipeline_name}",
            f"- **Priority:** {case.priority}",
            f"- **Type:** {case.test_type.value}",
            f"- **Quality dimension:** {case.quality_dimension.value}",
            f"- **Table / column:** {case.table_name or '—'} / {case.column_name or '—'}",
            f"- **Requirements:** {', '.join(case.requirement_ids) or '—'}",
            f"- **Data-quality rules:** {', '.join(case.data_quality_ids) or '—'}",
            f"- **Automation candidate:** {case.automation_candidate.value}"
            + (f" — {case.automation_rationale}" if case.automation_rationale else ""),
            f"- **Tags:** {', '.join(case.tags) or '—'}",
            "",
            f"**Objective:** {case.objective or '—'}",
            "",
        ]
        if case.preconditions:
            lines += ["**Preconditions:**", *[f"- {p}" for p in case.preconditions], ""]
        if case.test_data:
            lines += ["**Test data:**", *[f"- {d}" for d in case.test_data], ""]
        lines += ["| # | Action | Expected |", "| --- | --- | --- |"]
        for step in case.steps:
            lines.append(f"| {step.number} | {_cell(step.action)} | {_cell(step.expected) or '—'} |")
        lines += ["", f"**Expected result:** {case.expected_result or '—'}", ""]
        if case.sql_template:
            lines += ["**SQL template:**", "", f"```sql\n{case.sql_template.strip()}\n```", ""]
        if case.assumptions_or_blockers:
            lines += [
                "**Assumptions / blockers:**",
                *[f"- {b}" for b in case.assumptions_or_blockers],
                "",
            ]
    return "\n".join(lines)


def render_pytest_md(bundle: PytestBundle) -> str:
    lines = [
        f"# pytest Automation — {bundle.pipeline_name}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Automation readiness:** `{bundle.readiness.value}`",
        "",
    ]
    if bundle.readiness.value == "NEEDS_CONFIGURATION":
        lines += [
            "> This code imports cleanly but is **not execution-ready**. The "
            "items under Missing Information must be supplied first.",
            "",
        ]
    if bundle.setup_notes:
        lines += ["## Setup", "", bundle.setup_notes.strip(), ""]

    if bundle.traces:
        lines += [
            "## Coverage",
            "",
            "| Test | Test case | Requirements | Data-quality rules | File |",
            "| --- | --- | --- | --- | --- |",
        ]
        for trace in bundle.traces:
            lines.append(
                f"| {_cell(trace.test_name)} | {trace.test_case_id} | "
                f"{', '.join(trace.requirement_ids) or '—'} | "
                f"{', '.join(trace.data_quality_ids) or '—'} | {trace.file_path or '—'} |"
            )
        lines.append("")

    lines += ["## Generated files", ""]
    for file in bundle.files:
        lines += [f"### `{file.path}`", "", "```python", file.content.rstrip(), "```", ""]

    for title, values in (
        ("Missing Information", bundle.missing_information),
        ("Assumptions", bundle.assumptions),
    ):
        lines += [f"## {title}", ""]
        lines += [f"- {v}" for v in values] or ["_none_"]
        lines.append("")
    return "\n".join(lines)


def render_run_summary_md(run: RunSummary) -> str:
    lines = [
        "# Run Summary",
        "",
        f"**Run ID:** {run.run_id}",
        f"**Started:** {_stamp(run.started_at)}",
        f"**Finished:** {_stamp(run.finished_at)}",
        "",
        f"- Pipelines requested: {len(run.requested_pipelines)}",
        f"- Completed: {len(run.completed)}",
        f"- Completed with warnings: {len(run.completed_with_warnings)}",
        f"- Failed: {len(run.failed)}",
        "",
    ]
    if run.invalid_inputs:
        lines += [f"- Rejected input tokens: {', '.join(run.invalid_inputs)}", ""]
    if run.duplicates_removed:
        lines += [f"- Duplicates removed: {', '.join(run.duplicates_removed)}", ""]

    lines += [
        "| Pipeline | Status | Source | Automation | Reqs | DQ rules | Test cases | Coverage |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for result in run.results:
        coverage = (
            f"{result.coverage.requirement_coverage_pct}%" if result.coverage else "—"
        )
        lines.append(
            f"| {result.pipeline_name} | {result.status.value} | "
            f"{result.source.value if result.source else '—'} | "
            f"{result.pytest.readiness.value if result.pytest else '—'} | "
            f"{result.coverage.total_requirements if result.coverage else 0} | "
            f"{result.coverage.total_data_quality if result.coverage else 0} | "
            f"{result.coverage.total_test_cases if result.coverage else 0} | {coverage} |"
        )
    lines.append("")

    failures = run.failed
    if failures:
        lines += ["## Failures", ""]
        for result in failures:
            lines.append(f"- **{result.pipeline_name}**: {result.error}")
        lines.append("")

    warned = [r for r in run.results if r.warnings]
    if warned:
        lines += ["## Warnings", ""]
        for result in warned:
            lines.append(f"- **{result.pipeline_name}**")
            lines += [f"  - {w}" for w in result.warnings]
        lines.append("")
    return "\n".join(lines)


